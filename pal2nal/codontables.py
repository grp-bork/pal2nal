"""Reverse-translation tables: amino acid -> pattern of matching codons.

Tables 1-23 are transcribed from the %p2c hashes of pal2nal.v14.pl; tables
24-37 were added in v15 and are derived from the NCBI and Wikipedia sources
described under PROVENANCE below. A pattern matches a codon rather than the
other way round, which is
how pal2nal locates the codon for an aligned residue; the alternatives
spell out IUPAC ambiguity (``U|T`` for RNA input, ``A|G|R`` for purines,
``U|T|C|Y`` for pyrimidines) and ``.`` stands for a fully degenerate third
position, so ambiguity codes in the input DNA still match.

Two keys are not amino acids:

``B``
    the initiation codons of the table. pal2nal v14 treats the initiating
    Met separately from internal Met, which is what lets a gene starting
    at GTG or TTG be recognised.
``X``
    any codon.

``*`` and ``_`` are both accepted for an in-frame stop.

Tables 3, 10, 11 and 13 differ deliberately from pal2nal v14; see
MODIFIED_TABLES.

Every table here is checked against NCBI's own ``gc.prt`` on all 64 codons
by ``tests/test_codontables.py``, which is the check that identified the
table 10 defect in the first place.
"""

