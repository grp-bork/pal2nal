def compile_table(codontable: int) -> dict[str, re.Pattern[str]]:
    """Compile one genetic code's patterns, anchored to a whole codon."""
    try:
        table = P2C[codontable]
    except KeyError:
        raise ValueError(f"unsupported codon table: {codontable}") from None
    return {aa: re.compile(pat + r"\Z") for aa, pat in table.items()}
