#: ``wikipedia``
#:     The four codes found by Shulgina & Eddy (2021, eLife 10:e71402) and
#:     listed by Wikipedia's "List of genetic codes" as 34-37. NCBI has *not*
#:     adopted them and has assigned no ids past 33, so these numbers are
